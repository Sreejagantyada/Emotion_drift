class TextDataset(Dataset):
    def __init__(self, encodings, labels):
        self.encodings = encodings
        self.labels = labels
    def __len__(self):
        return len(self.labels)
    def __getitem__(self, idx):
        item = {k: torch.tensor(v[idx]) for k, v in self.encodings.items()}
        item["labels"] = torch.tensor(self.labels[idx])
        return item

def clear_gpu():
    gc.collect()
    torch.cuda.empty_cache()

def train_and_save(model_name, save_name, use_fp16=True):
    clear_gpu()

    tokenizer = AutoTokenizer.from_pretrained(model_name)
    model = AutoModelForSequenceClassification.from_pretrained(model_name, num_labels=2)

    train_enc = tokenizer(list(train_df['english_text']), truncation=True, padding=True)
    val_enc   = tokenizer(list(val_df['english_text']), truncation=True, padding=True)

    train_ds = TextDataset(train_enc, list(train_df['manipulative_label']))
    val_ds   = TextDataset(val_enc, list(val_df['manipulative_label']))

    def compute_metrics(eval_pred):
        logits, labels = eval_pred
        preds = np.argmax(logits, axis=1)
        probs = torch.softmax(torch.tensor(logits), dim=1)[:,1].numpy()
        return {
            "accuracy": accuracy_score(labels, preds),
            "f1": f1_score(labels, preds),
            "roc_auc": roc_auc_score(labels, probs)
        }

    training_args = TrainingArguments(
        output_dir=save_name,
        num_train_epochs=2,
        per_device_train_batch_size=2,
        per_device_eval_batch_size=2,
        gradient_accumulation_steps=2,
        fp16=use_fp16,
        eval_strategy="epoch",
        save_strategy="no"
    )

    trainer = Trainer(
        model=model,
        args=training_args,
        train_dataset=train_ds,
        eval_dataset=val_ds,
        compute_metrics=compute_metrics
    )

    trainer.train()

    os.makedirs(save_name, exist_ok=True)
    model.save_pretrained(save_name)
    tokenizer.save_pretrained(save_name)

    print(f"Saved {save_name}")
    return save_name

