def semantic_drift(e1, e2):
    return 1 - np.diag(cosine_similarity(e1, e2))

def jsd(p, q):
    return jensenshannon(p, q)**2

probs_eng = np.stack([
    1 - full_df["manipulative_label"].values,
    full_df["manipulative_label"].values
], axis=1)

def compute_all(emb, probs):
    res = {}
    for lang in ["hindi_translit","tamil_translit","telugu_translit"]:
        sem = semantic_drift(emb["english_text"], emb[lang])
        emo = np.array([jsd(p, q) for p, q in zip(probs_eng, probs[lang])])
        res[lang] = (sem.mean(), emo.mean())
    return res

